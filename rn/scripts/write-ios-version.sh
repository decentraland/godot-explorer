#!/usr/bin/env bash
# Write rn/ios/Version.generated.xcconfig: MARKETING_VERSION from lib/Cargo.toml (the version the
# store sees, kept in sync with export_presets.cfg by bump_version.yml) and CURRENT_PROJECT_VERSION
# from DCL_BUILD_NUMBER (the CI build-number allocator), 1 when unset.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
VERSION="$(sed -n 's/^version = "\(.*\)"/\1/p' "$ROOT/lib/Cargo.toml" | head -1)"
BUILD="${DCL_BUILD_NUMBER:-1}"

printf '// Generated by rn/scripts/write-ios-version.sh; do not edit.\nMARKETING_VERSION = %s\nCURRENT_PROJECT_VERSION = %s\n' \
  "$VERSION" "$BUILD" > "$ROOT/rn/ios/Version.generated.xcconfig"
echo "iOS version $VERSION ($BUILD)"
