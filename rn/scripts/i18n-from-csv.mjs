#!/usr/bin/env node
// Generates rn/src/i18n/{es,pt_BR}/<area>.ts from godot/locale/<locale>.csv, following the key tables in
// rn/src/i18n/en/. Keys with no translation stay out and fall back to English at runtime.
//
//   node scripts/i18n-from-csv.mjs           write the files
//   node scripts/i18n-from-csv.mjs --check   fail if the files are stale or a translation changes the
//                                            placeholders of its English text; print what is untranslated
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const i18n = path.join(root, 'src', 'i18n');
const csvDir = path.join(root, '..', 'godot', 'locale');
const LOCALES = ['es', 'pt_BR'];
const check = process.argv.includes('--check');

/** Semicolon CSV with quoted fields (`""` escapes a quote; fields may span lines). */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') {
        quoted = false;
      } else {
        field += c;
      }
    } else if (c === '"') {
      quoted = true;
    } else if (c === ';') {
      row.push(field);
      field = '';
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') {
        i++;
      }
      row.push(field);
      field = '';
      if (row.length > 1 || row[0] !== '') {
        rows.push(row);
      }
      row = [];
    } else {
      field += c;
    }
  }
  if (field !== '' || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

const placeholders = s =>
  [...s.matchAll(/\{(\w+)\}/g)].map(m => m[1]).sort().join(',');

/** The area tables: `export const hud = { KEY: 'text', ... }` in en/<area>.ts, key order kept. */
function areas() {
  const dir = path.join(i18n, 'en');
  return fs
    .readdirSync(dir)
    .filter(f => f.endsWith('.ts') && f !== 'index.ts')
    .sort()
    .map(f => {
      const source = fs.readFileSync(path.join(dir, f), 'utf8');
      const name = source.match(/export const (\w+) =/)[1];
      return { file: f, name, keys: [...source.matchAll(/^ {2}([A-Z0-9_]+):/gm)].map(m => m[1]) };
    });
}

/** RN's own English text, for the placeholder comparison; read from the area files. */
function rnEnglish() {
  const text = {};
  for (const area of areas()) {
    const source = fs.readFileSync(path.join(i18n, 'en', area.file), 'utf8');
    for (const m of source.matchAll(
      /^ {2}([A-Z0-9_]+):\s*\n?\s*'((?:[^'\\]|\\.)*)'/gm,
    )) {
      text[m[1]] = m[2].replace(/\\'/g, "'").replace(/\\n/g, '\n');
    }
  }
  return text;
}

const render = (area, translated) => {
  const body = area.keys
    .filter(k => k in translated)
    .map(k => `  ${k}: ${JSON.stringify(translated[k])},`)
    .join('\n');
  return `// Generated by scripts/i18n-from-csv.mjs from godot/locale; do not edit.\nimport type { ${area.name} as en } from '../en/${area.file.replace(/\.ts$/, '')}';\n\nexport const ${area.name}: Partial<Record<keyof typeof en, string>> = {\n${body}\n};\n`;
};

const indexSource = areaList =>
  `// Generated by scripts/i18n-from-csv.mjs; do not edit.\n${areaList
    .map(a => `import { ${a.name} } from './${a.file.replace(/\.ts$/, '')}';`)
    .join('\n')}\n\nexport const table: Record<string, string> = {\n${areaList
    .map(a => `  ...${a.name},`)
    .join('\n')}\n};\n`;

const areaList = areas();
const rn = rnEnglish();
const problems = [];
const report = [];
const generated = [];

for (const locale of LOCALES) {
  const rows = parseCsv(
    fs.readFileSync(path.join(csvDir, `${locale}.csv`), 'utf8'),
  ).slice(2);
  const csv = {};
  for (const [key, , , text] of rows) {
    if (text) {
      csv[key] = text;
    }
  }
  let missing = 0;
  for (const area of areaList) {
    const translated = {};
    for (const key of area.keys) {
      if (!(key in csv)) {
        missing++;
        continue;
      }
      if (key in rn && placeholders(rn[key]) !== placeholders(csv[key])) {
        problems.push(`${locale} ${key}: placeholders differ from English`);
        continue;
      }
      translated[key] = csv[key];
    }
    generated.push([
      path.join(i18n, locale, area.file),
      render(area, translated),
    ]);
  }
  generated.push([path.join(i18n, locale, 'index.ts'), indexSource(areaList)]);
  report.push(`${locale}: ${missing} of ${Object.keys(rn).length} keys untranslated (English fallback)`);
}

const prettier = files => {
  execFileSync('npx', ['prettier', '--write', ...files], {
    cwd: root,
    stdio: 'ignore',
  });
};

if (check) {
  const stale = [];
  const tmp = fs.mkdtempSync(path.join(root, '.i18n-check-'));
  try {
    const staged = generated.map(([file, text], i) => {
      const copy = path.join(tmp, `${i}.ts`);
      fs.writeFileSync(copy, text);
      return [file, copy];
    });
    prettier(staged.map(([, copy]) => copy));
    for (const [file, copy] of staged) {
      if (
        !fs.existsSync(file) ||
        fs.readFileSync(file, 'utf8') !== fs.readFileSync(copy, 'utf8')
      ) {
        stale.push(path.relative(root, file));
      }
    }
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
  report.forEach(line => console.log(line));
  if (stale.length) {
    problems.push(
      `stale generated files (run node scripts/i18n-from-csv.mjs): ${stale.join(', ')}`,
    );
  }
  if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
} else {
  for (const locale of LOCALES) {
    fs.mkdirSync(path.join(i18n, locale), { recursive: true });
  }
  for (const [file, text] of generated) {
    fs.writeFileSync(file, text);
  }
  prettier(generated.map(([file]) => file));
  report.forEach(line => console.log(line));
  problems.forEach(line => console.warn(`skipped: ${line}`));
}
