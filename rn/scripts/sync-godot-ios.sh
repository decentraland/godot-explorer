#!/usr/bin/env bash
# Copy the Godot engine (built with embedded_host=yes), the exported project pack, the plugin glue
# and the GDExtension frameworks into rn/ios/Godot, and write the godot.xcconfig that links them.
# Without rn/ios/Godot the app still builds and runs with the JS mock bridge. macOS only.
#
# Needs, from the repo root:
#   GODOT_HOST_LIB=<path to libgodot.ios.template_*.arm64.a built with embedded_host=yes>
#   cargo run -- build -r --target ios && cargo run -- export --target ios --release
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
EXPORT="${GODOT_IOS_EXPORT:-$ROOT/exports}"
APP="$EXPORT/decentraland-godot-client"
DEST="$ROOT/rn/ios/Godot"
: "${GODOT_HOST_LIB:?set GODOT_HOST_LIB to the embedded_host libgodot .a}"
[ -f "$EXPORT/decentraland-godot-client.pck" ] || { echo "missing $EXPORT/decentraland-godot-client.pck (run: cargo run -- export --target ios --release)"; exit 1; }

rm -rf "$DEST"
mkdir -p "$DEST/lib" "$DEST/Frameworks"

cp "$GODOT_HOST_LIB" "$DEST/lib/libgodot.a"
cp "$EXPORT/MoltenVK.xcframework/ios-arm64/libMoltenVK.a" "$DEST/lib/"
cp "$APP"/dylibs/ios/plugins/dcl_godot_ios/dcl_godot_ios.xcframework/ios-arm64/*.a "$DEST/lib/libdcl_godot_ios.a"
cp "$EXPORT/decentraland-godot-client.pck" "$DEST/project.pck"
# Generated by the exporter: godot_apple_embedded_plugins_initialize (DclGodotiOS).
cp "$APP/dummy.cpp" "$DEST/godot_plugins.cpp"
# Host-only: a translucent Godot surface lets the avatar preview draw above the RN UI.
printf '[display]\n\nwindow/per_pixel_transparency/allowed=true\n' > "$DEST/override.cfg"

# Debug exports carry the scene-inspector / remote-debug command line in the generated plist.
PLIST="$APP/decentraland-godot-client-Info.plist"
if plutil -extract godot_cmdline json -o - "$PLIST" > /dev/null 2>&1; then
  plutil -extract godot_cmdline json -o - "$PLIST" | python3 -c 'import json,sys; print("\n".join(json.load(sys.stdin)))' > "$DEST/godot_cmdline.txt"
fi

# GDExtensions load from <bundle>/Frameworks/<name>.framework; only the device slices are needed.
cp -R "$APP/lib/target/libdclgodot_ios/libdclgodot.framework" "$DEST/Frameworks/"
cp -R "$APP/dylibs/ios/dcl-swift-lib/DclSwiftLib.framework" "$DEST/Frameworks/"

# System frameworks the DclGodotiOS plugin and the engine need (as in the exported project).
SYSTEM_FRAMEWORKS="SafariServices AuthenticationServices Network EventKit EventKitUI DeviceCheck Photos PhotosUI StoreKit GameController CoreHaptics CoreMotion"
cat > "$DEST/godot.xcconfig" <<XCCONFIG
// Generated by rn/scripts/sync-godot-ios.sh; do not edit.
DCL_GODOT_DIR = \$(SRCROOT)/Godot
DCL_GODOT_DEFINES[sdk=iphoneos*] = DCL_WITH_GODOT=1
DCL_GODOT_LDFLAGS[sdk=iphoneos*] = -force_load \$(DCL_GODOT_DIR)/lib/libgodot.a \$(DCL_GODOT_DIR)/lib/libMoltenVK.a \$(DCL_GODOT_DIR)/lib/libdcl_godot_ios.a -F\$(DCL_GODOT_DIR)/Frameworks $(for f in $SYSTEM_FRAMEWORKS; do printf -- '-framework %s ' "$f"; done)
XCCONFIG

echo "synced into $DEST: $(du -sh "$DEST" | cut -f1), frameworks: $(ls "$DEST/Frameworks" | tr '\n' ' ')"

"$ROOT/rn/scripts/write-ios-version.sh"
