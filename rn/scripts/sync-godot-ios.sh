#!/usr/bin/env bash
# VIBE-CODED SPIKE: copy the Godot engine (built with embedded_host=yes), the exported project
# pack, the plugin glue and the GDExtension frameworks into rn/ios/Godot. macOS only.
#
# Needs, from the repo root:
#   GODOT_HOST_LIB=<path to libgodot.ios.template_*.arm64.a built with embedded_host=yes>
#   cargo run -- build -r --target ios && cargo run -- export --target ios --release
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
EXPORT="$ROOT/exports"
APP="$EXPORT/decentraland-godot-client"
DEST="$ROOT/rn/ios/Godot"
: "${GODOT_HOST_LIB:?set GODOT_HOST_LIB to the embedded_host libgodot .a}"
[ -f "$EXPORT/decentraland-godot-client.pck" ] || { echo "missing export (run: cargo run -- export --target ios --release)"; exit 1; }

rm -rf "$DEST"
mkdir -p "$DEST/Frameworks" "$DEST/XCFrameworks"

cp "$GODOT_HOST_LIB" "$DEST/libgodot.a"
cp "$EXPORT/MoltenVK.xcframework/ios-arm64/libMoltenVK.a" "$DEST/"
# The engine looks for <host executable>.pck in the bundle root, and the executable is DclRn.
cp "$EXPORT/decentraland-godot-client.pck" "$DEST/DclRn.pck"
# Generated by the exporter: godot_apple_embedded_plugins_initialize (DclGodotiOS) and the
# statically registered Sentry GDExtension entry point. libgodot.a needs both symbols.
cp "$APP/dummy.cpp" "$DEST/godot_plugins.cpp"
# Host-only: a translucent Godot surface lets the avatar preview draw above the RN UI.
printf '[display]\n\nwindow/per_pixel_transparency/allowed=true\n' > "$DEST/override.cfg"

# GDExtensions load from <bundle>/Frameworks/<name>.framework.
cp -R "$APP/lib/target/libdclgodot_ios/libdclgodot.framework" "$DEST/Frameworks/"
cp -R "$APP/dylibs/ios/dcl-swift-lib/DclSwiftLib.framework" "$DEST/Frameworks/"
cp -R "$APP/dylibs/ios/plugins/dcl_godot_ios/dcl_godot_ios.xcframework" "$DEST/XCFrameworks/"
cp -R "$APP/dylibs/addons/sentry/bin/ios/libsentry.ios.release.xcframework" "$DEST/XCFrameworks/"
cp -R "$APP/dylibs/addons/sentry/bin/ios/Sentry.xcframework" "$DEST/XCFrameworks/"

echo "synced into $DEST: $(du -sh "$DEST" | cut -f1)"
